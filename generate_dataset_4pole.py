# ── Training configuration (seed, samples/tissue, variation, noise, thickness [m]) ─────
TRAIN = dict(seed=42, n=1000, var=0.15, a_abs=0.03, snr=45, mult=0.02, thick=0.030)


def sample_params(p, n, rng, var, a_abs):
    """Nominal etrafında bağımsız varyasyon (tüm kutuplar). ε∞ için ±(2/3)·var."""
    def mult(v, frac):
        return v * rng.uniform(1 - frac, 1 + frac, n) if v != 0 else np.zeros(n)
    P = {"ef": mult(p["ef"], var * 2 / 3), "sig": mult(p["sig"], var)}
    for k, (dk, tk, ak) in enumerate([("d1", "t1_ps", "a1"), ("d2", "t2_ns", "a2"),
                                       ("d3", "t3_us", "a3"), ("d4", "t4_ms", "a4")], 1):
        P[f"d{k}"] = mult(p[dk], var)
        P[f"t{k}"] = mult(p[tk], var)                   # birim: ps/ns/us/ms
        P[f"a{k}"] = np.clip(p[ak] + rng.uniform(-a_abs, a_abs, n), 0.0, 0.5)
    return P


def eps_4pole(P):
    """(N, F) karmaşık bağıl permittivite. ε = ε∞ + Σ Δε/(1+(jωτ)^(1-α)) − jσ/(ωε0)."""
    unit = {1: 1e-12, 2: 1e-9, 3: 1e-6, 4: 1e-3}
    w = OMEGA[None, :]
    e = P["ef"][:, None] + 0j
    for k in (1, 2, 3, 4):
        d, a = P[f"d{k}"][:, None], P[f"a{k}"][:, None]
        t = P[f"t{k}"][:, None] * unit[k]
        e = e + np.where(d > 0, d / (1 + (1j * w * t) ** (1 - a)), 0.0)
    return e - 1j * P["sig"][:, None] / (w * e0)


def s21_slab(e, d):
    """Düz levha iletimi (dik geliş, μ=1): S21 = (1-Γ²)z / (1-Γ²z²)."""
    n = np.sqrt(e)
    n = np.where(np.imag(n) > 0, np.conj(n), n)
    z = np.exp(-1j * n * (OMEGA / c)[None, :] * d[:, None])
    G = (1 - n) / (1 + n)
    return np.abs(((1 - G ** 2) * z) / (1 - G ** 2 * z ** 2))


def add_noise(S, rng, snr_db, mult):
    """AWGN (SNR, spektrumun TÜM bant ortalama gücüne göre) + çarpımsal gürültü."""
    pw  = np.mean(S ** 2, axis=1, keepdims=True)
    Sn  = np.clip(S + rng.normal(0, 1, S.shape) * np.sqrt(pw / 10 ** (snr_db / 10)), 1e-6, 1.0)
    return np.clip(Sn * rng.normal(1.0, mult, S.shape), 1e-6, 1.0)


def generate(cfg, scenario):
    rng = np.random.default_rng(cfg["seed"])
    frames = []
    for tissue, p in ITIS_4POLE.items():
        n = cfg["n"]
        P = sample_params(p, n, rng, cfg["var"], cfg["a_abs"])
        d = np.full(n, cfg["thick"])
        e = eps_4pole(P)
        S = add_noise(s21_slab(e, d), rng, cfg["snr"], cfg["mult"])
        df = pd.DataFrame({
            "tissue": tissue, "scenario": scenario,
            # 1. kutup + statik iyonik iletkenlik (v2 ile aynı sütun adları)
            "eps_inf": P["ef"], "delta_eps1": P["d1"], "tau1_ps": P["t1"],
            "alpha1": P["a1"], "sigma": P["sig"],
            # diğer kutuplar
            "delta_eps2": P["d2"], "tau2_ns": P["t2"], "alpha2": P["a2"],
            "delta_eps3": P["d3"], "tau3_us": P["t3"], "alpha3": P["a3"],
            "delta_eps4": P["d4"], "tau4_ms": P["t4"], "alpha4": P["a4"],
            "thickness_m": d, "snr_db": cfg["snr"], "mult_noise": cfg["mult"]})
        # fiziksel olarak tanımlı (tanımlanabilir) hedefler: ε′(f), σ_eff(f)
        for f, i in zip(TARGET_F, TARGET_IDX):
            tag = str(f).replace(".", "p")
            df[f"epsr_f{tag}"]   = e[:, i].real
            df[f"sigeff_f{tag}"] = -e[:, i].imag * OMEGA[i] * e0
        S21 = pd.DataFrame(S, columns=[f"s21_{i:03d}" for i in range(len(FREQ_GHz))])
        frames.append(pd.concat([df.reset_index(drop=True), S21], axis=1))
    return pd.concat(frames, ignore_index=True)


